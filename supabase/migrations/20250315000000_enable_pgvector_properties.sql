-- Sprint 5: enable pgvector and create the sample `properties` table for semantic search.
-- Source of truth: docs/embedding-data-model.md and docs/pgvector-setup-plan.md.
-- This migration ONLY creates new objects. It does not touch `property_listings`,
-- `profiles`, or any existing data, and it adds no seed rows (those come later).

-- ---------------------------------------------------------------------------
-- 1) Enable pgvector
-- ---------------------------------------------------------------------------
-- pgvector is an optional PostgreSQL add-on. It adds the `vector` column type
-- (an ordered list of numbers that stands for the meaning of some text) and
-- operators like `<=>` (cosine distance) to compare two vectors.
-- It must run BEFORE the table below, or Postgres says "type vector does not exist".
-- Safe to re-run: IF NOT EXISTS skips it if pgvector is already on.
-- Supabase keeps extensions in the `extensions` schema (already on the search path).
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA extensions;

-- ---------------------------------------------------------------------------
-- 2) Sample properties table (columns copied from docs/embedding-data-model.md)
-- ---------------------------------------------------------------------------
-- One row = one sample investment listing shown in semantic search.
-- The readable text (title, description) and the meaning vector (embedding)
-- are separate columns: text is for people and for re-embedding,
-- the vector is for ranking by closeness of meaning.
CREATE TABLE IF NOT EXISTS public.properties (
  -- Primary key: unique id for each listing, generated by the database.
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Embedding input = title + blank line + description (see data model doc).
  title text NOT NULL CHECK (length(btrim(title)) > 0),
  description text NOT NULL CHECK (length(btrim(description)) > 0),

  -- Display-only fields. NOT embedded, not used for ranking or filtering.
  city text,
  property_type text,
  price integer CHECK (price IS NULL OR price >= 0),  -- whole US dollars

  -- Meaning vector: 1536 numbers from OpenAI text-embedding-3-small
  -- (the data model's DIMENSION_TODO = 1536).
  -- NULL until the seed/backfill step generates it; NULL rows are not searchable.
  -- Do NOT change 1536 here without also changing the data model doc and the
  -- TypeScript embedding module, or inserts and search will break.
  embedding extensions.vector(1536),

  created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.properties IS
  'PREIshare sample listings for semantic search; embedding powers meaning-based ranking.';
COMMENT ON COLUMN public.properties.embedding IS
  'pgvector embedding of title + blank line + description; dimension 1536 (text-embedding-3-small); null until seeded.';

-- ---------------------------------------------------------------------------
-- 3) Row-Level Security: read-only for the app, no writes from the browser
-- ---------------------------------------------------------------------------
-- Supabase exposes public tables through its API, so RLS is turned on right away.
-- Sample listings are public demo data, so anyone may READ them.
-- There are no insert/update/delete policies: seeding happens later from the
-- SQL editor or trusted server code, never from the browser.
ALTER TABLE public.properties ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS properties_select_public ON public.properties;
CREATE POLICY properties_select_public
  ON public.properties
  FOR SELECT
  TO anon, authenticated
  USING (true);

